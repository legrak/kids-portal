export type Region = "europe" | "asia" | "africa" | "northAmerica" | "southAmerica" | "oceania";

/**
 * How well known a country is to a kid in Ukraine.
 * - famous: the small "well-known countries" set;
 * - regular: shown in the full game;
 * - excluded: tiny island states and countries a kid in Ukraine hardly ever hears of, never shown.
 */
export type Tier = "famous" | "regular" | "excluded";

export interface LocalizedNames {
  name: string;
  /** Other accepted spellings of the name. */
  aliases?: readonly string[];
  capital: string;
  /** Other accepted spellings of the capital, or other capitals of a country that has several. */
  capitalAliases?: readonly string[];
}

export interface Country {
  /** ISO 3166-1 alpha-2 code, lowercase; also the flag file name in flag-icons. */
  code: string;
  /** ISO 3166-1 numeric code; also the feature id in world-atlas. */
  isoNumeric: string;
  region: Region;
  tier: Tier;
  uk: LocalizedNames;
  en: LocalizedNames;
}

